// 1. INVOICE KEUANGAN BULANAN
function downloadMonthlyInvoicePDF() {
  const bulanStr = document.getElementById('filterBulan').value;
  if (!bulanStr) { showToast('Pilih bulan terlebih dahulu!'); return; }
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();

  doc.setFillColor(30, 27, 75);
  doc.rect(0, 0, 210, 42, 'F');
  try {
    const imgEl = document.getElementById('headerAvatar');
    if (imgEl && imgEl.complete) doc.addImage(imgEl, 'PNG', 14, 9, 24, 24);
  } catch (e) {}

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16); doc.setFont('helvetica', 'bold');
  doc.text('MONTHLY FINANCIAL STATEMENT', 44, 18);
  doc.setFontSize(9); doc.setFont('helvetica', 'normal'); doc.setTextColor(199, 210, 254);
  doc.text(`Account Holder: ${userProfile.name} (${userProfile.bio})`, 44, 25);
  doc.text(`Statement Period: ${bulanStr}  |  Generated by Ezar Tracker v6.0`, 44, 31);

  const listBulan = dataKeuangan.filter(k => k.tanggal.startsWith(bulanStr));
  let totMasuk = 0, totKeluar = 0, totTabung = 0;
  listBulan.forEach(k => {
    if (k.jenis === 'Transfer') return;
    if (k.kategori === 'Tabungan') totTabung += k.nominal;
    else if (k.jenis === 'Pemasukan') totMasuk += k.nominal;
    else totKeluar += k.nominal;
  });

  doc.setTextColor(30, 41, 59); doc.setFontSize(10); doc.setFont('helvetica', 'bold');
  doc.text('RINGKASAN ARUS KAS REAL (NON-TRANSFER)', 14, 52);

  doc.autoTable({
    startY: 55,
    head: [['Total Pemasukan', 'Total Pengeluaran', 'Setoran Tabungan', 'Selisih Bersih (Net)']],
    body: [[formatRupiah(totMasuk), formatRupiah(totKeluar), formatRupiah(totTabung), formatRupiah(totMasuk - totKeluar)]],
    theme: 'grid',
    headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: 'bold', halign: 'center' },
    bodyStyles: { halign: 'center', fontStyle: 'bold', fontSize: 10 }
  });

  const rows = listBulan.map((k, i) => {
    const akun = k.jenis === 'Transfer' ? `${k.dompet} -> ${k.dompet_tujuan}` : (k.dompet || 'Tunai');
    const prefix = k.jenis === 'Transfer' ? '⇄ ' : (k.jenis === 'Pemasukan' ? '+ ' : '- ');
    return [i + 1, k.tanggal, k.jenis, k.kategori, akun, k.catatan, prefix + formatRupiah(k.nominal)];
  });

  doc.autoTable({
    startY: doc.lastAutoTable.finalY + 10,
    head: [['No', 'Tanggal', 'Jenis', 'Kategori', 'Akun', 'Catatan', 'Nominal']],
    body: rows.length ? rows : [['-', '-', '-', 'Tidak ada transaksi', '-', '-', 'Rp 0']],
    theme: 'striped',
    headStyles: { fillColor: [30, 41, 59], textColor: 255, fontSize: 8 },
    bodyStyles: { fontSize: 8 }
  });

  doc.save(`Statement-EzarTracker-${bulanStr}.pdf`);
  showToast(`Invoice PDF ${bulanStr} diunduh!`);
}

// 2. KARTU JADWAL KULIAH MINGGUAN PDF
function downloadJadwalPDF() {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();
  doc.setFillColor(79, 70, 229);
  doc.rect(0, 0, 210, 34, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(15); doc.setFont('helvetica', 'bold');
  doc.text('KARTU JADWAL PERKULIAHAN MINGGUAN', 14, 15);
  doc.setFontSize(9); doc.setFont('helvetica', 'normal');
  doc.text(`${userProfile.name}  |  ${userProfile.bio}  |  Total ${TOTAL_PERTEMUAN} Pertemuan`, 14, 24);

  const hariUrut = ['Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
  const sorted = [...dataJadwal].sort((a, b) => hariUrut.indexOf(a.hari) - hariUrut.indexOf(b.hari) || a.jam_mulai.localeCompare(b.jam_mulai));

  doc.autoTable({
    startY: 42,
    head: [['Hari', 'Jam', 'Kode', 'Mata Kuliah', 'Ruangan', 'Dosen', 'Hadir']],
    body: sorted.map(j => [j.hari, `${j.jam_mulai}-${j.jam_selesai}`, j.kode_matkul, j.nama_matkul, j.ruangan, j.dosen, `${j.hadir || 0}/${TOTAL_PERTEMUAN}`]),
    theme: 'grid',
    headStyles: { fillColor: [30, 27, 75], textColor: 255, fontSize: 8 },
    bodyStyles: { fontSize: 8 }
  });

  doc.save(`Jadwal-Kuliah-${userProfile.name.replace(/\s+/g, '_')}.pdf`);
  showToast('Kartu Jadwal Kuliah PDF berhasil diunduh!');
}

// 3. TRANSKRIP SIMULASI IPK PDF
function downloadTranskripPDF() {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF();
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 34, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(15); doc.setFont('helvetica', 'bold');
  doc.text('TRANSKRIP PROYEKSI NILAI & IPK', 14, 15);
  doc.setFontSize(9); doc.setFont('helvetica', 'normal');
  doc.text(`${userProfile.name}  |  ${userProfile.bio}`, 14, 24);

  let totalSks = 0, totalMutu = 0;
  const rows = dataNilai.map((n, i) => {
    const akhir = (n.tugas * 0.3) + (n.uts * 0.35) + (n.uas * 0.35);
    const g = getGradeInfo(akhir);
    totalSks += n.sks; totalMutu += (g.bobot * n.sks);
    return [i + 1, n.kode_matkul, n.nama_matkul, n.sks, n.tugas, n.uts, n.uas, akhir.toFixed(1), g.huruf];
  });
  const ips = totalSks > 0 ? (totalMutu / totalSks).toFixed(2) : '0.00';

  doc.autoTable({
    startY: 42,
    head: [['No', 'Kode', 'Mata Kuliah', 'SKS', 'Tugas', 'UTS', 'UAS', 'Akhir', 'Indeks']],
    body: rows,
    foot: [['', '', 'TOTAL SKS & PROYEKSI IPS / IPK', totalSks, '', '', '', 'IPS:', ips]],
    theme: 'striped',
    headStyles: { fillColor: [79, 70, 229], textColor: 255, fontSize: 8 },
    footStyles: { fillColor: [241, 245, 249], textColor: [15, 23, 42], fontStyle: 'bold' },
    bodyStyles: { fontSize: 8 }
  });

  doc.save(`Transkrip-Simulasi-IPK-${userProfile.name.replace(/\s+/g, '_')}.pdf`);
  showToast('Transkrip Simulasi IPK PDF diunduh!');
}